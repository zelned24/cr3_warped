"""Export the real Crash Bandicoot model (Cr10G) and animations (Cr10V, CrW0V, CJF1V, CrS1V)
into a compact C header file consumed by source/char.c on Nintendo 3DS.
"""
import os
import sys

TOOLS_DIR = os.path.dirname(os.path.abspath(__file__))
if TOOLS_DIR not in sys.path:
    sys.path.insert(0, TOOLS_DIR)

import cb3
import svtx
import tgeo
import anim
import tgeo_shading

def main(render_mode=None):
    tgeo_shading.require_rgb(render_mode)
    print("[export_crash] Loading level 0x0B archive...")
    arc = cb3.load_level(0x0B)
    g_entry = arc.entry("Cr10G")
    if not g_entry:
        raise RuntimeError("Cr10G entry not found in level 0x0B")
    
    tg = tgeo.parse_tgeo(g_entry)
    v_idle = arc.entry("Cr10V")
    v_walk = arc.entry("CrW0V")
    v_jump = arc.entry("CJF1V")
    v_spin = arc.entry("CrS1V")
    v_run = arc.entry("CrR0V")
    v_takeoff = arc.entry("CJS1V")
    v_jump_up = arc.entry("CJU1V")
    v_land = arc.entry("CJL1V")
    clips = {"idle": v_idle, "walk": v_walk, "run": v_run,
             "jump": v_jump, "takeoff": v_takeoff, "jump_up": v_jump_up,
             "land": v_land, "spin": v_spin}
    for name, entry in clips.items():
        if entry is None:
            raise RuntimeError("Required original animation missing: " + name)

    # Build reference mesh to get corner indices and vertex colors
    mesh = tgeo.build_mesh(tg, v_idle, render_mode=render_mode)
    corners = mesh["vertices"]
    tri_count = mesh["tri_count"]
    corner_count = len(corners)
    
    indices = [v["vtx_index"] for v in corners]
    colors = [v["color"] for v in corners]
    num_unique_verts = max(indices) + 1

    print(f"[export_crash] Triangles: {tri_count}, Corners: {corner_count}, Unique vertices: {num_unique_verts}")

    def extract_clip(entry, name):
        frames = svtx.parse_svtx(entry)
        clip_positions = []
        for fi, f in enumerate(frames):
            raw = svtx.generate_vertices(f, tg.compression)
            org = f.origin
            f_pts = []
            for vi in range(num_unique_verts):
                if vi < len(raw):
                    bx, by, bz = raw[vi]
                else:
                    bx, by, bz = 0, 0, 0
                # Authentic Crash Bandicoot scale matching level models & crates
                SCALE_FACTOR = 1.0
                px = ((bx + org[0]) * tg.scale[0] / 8.0) * SCALE_FACTOR
                py = ((by + org[1]) * tg.scale[1] / 8.0) * SCALE_FACTOR
                pz = ((bz + org[2]) * tg.scale[2] / 8.0) * SCALE_FACTOR
                f_pts.append((px, py, pz))
            clip_positions.append(f_pts)
        print(f"[export_crash] Clip '{name}': {len(frames)} frames extracted")
        return clip_positions

    anim_idle = extract_clip(v_idle, "idle")
    anim_walk = extract_clip(v_walk, "walk")
    anim_jump = extract_clip(v_jump, "jump")
    anim_spin = extract_clip(v_spin, "spin")
    anim_run = extract_clip(v_run, "run")
    anim_takeoff = extract_clip(v_takeoff, "takeoff")
    anim_jump_up = extract_clip(v_jump_up, "jump_up")
    anim_land = extract_clip(v_land, "land")

    out_path = os.path.join(os.path.dirname(TOOLS_DIR), "source", "crash_model.h")
    print(f"[export_crash] Writing C header to {out_path}...")

    with open(out_path, "w", encoding="utf-8") as f:
        f.write("/* Automatically generated by tools/export_crash.py - DO NOT EDIT */\n")
        f.write("#ifndef CRASH_MODEL_H\n#define CRASH_MODEL_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"#define CRASH_TRI_COUNT {tri_count}\n")
        f.write(f"#define CRASH_CORNER_COUNT {corner_count}\n")
        f.write(f"#define CRASH_NUM_VERTS {num_unique_verts}\n\n")
        f.write(f"#define CRASH_FRAMES_IDLE {len(anim_idle)}\n")
        f.write(f"#define CRASH_FRAMES_WALK {len(anim_walk)}\n")
        f.write(f"#define CRASH_FRAMES_JUMP {len(anim_jump)}\n")
        f.write(f"#define CRASH_FRAMES_SPIN {len(anim_spin)}\n\n")
        for name, data in (("run", anim_run), ("takeoff", anim_takeoff),
                           ("jump_up", anim_jump_up), ("land", anim_land)):
            f.write(f"#define CRASH_FRAMES_{name.upper()} {len(data)}\n")
        f.write("/* GOOL group lengths in logic ticks; runtime assumes 30 Hz. */\n")
        for name, entry in clips.items():
            group = anim.find_group(arc, entry.name)
            if group is None or group.frames <= 0:
                raise RuntimeError("Original GOOL timing missing: " + entry.name)
            f.write(f"#define CRASH_TICKS_{name.upper()} {group.frames}\n")
        f.write("\n")

        # Compact point struct
        f.write("typedef struct { float x, y, z; } crash_pt;\n")
        f.write("typedef struct { float r, g, b; } crash_col;\n\n")

        # Corner topology indices
        f.write("static const uint16_t crash_indices[CRASH_CORNER_COUNT] = {\n    ")
        for i, idx in enumerate(indices):
            f.write(f"{idx}, ")
            if (i + 1) % 16 == 0:
                f.write("\n    ")
        f.write("\n};\n\n")

        # RGB mode is supplied by native object context. Do not invent a
        # 1.35 lighting gain or treat packed normals as vertex colors.
        f.write("static const crash_col crash_colors[CRASH_CORNER_COUNT] = {\n")
        for i, (r, g, b) in enumerate(colors):
            lr, lg, lb = r, g, b
            f.write(f"    {{ {lr:.3f}f, {lg:.3f}f, {lb:.3f}f }},")
            if (i + 1) % 4 == 0:
                f.write("\n")
        f.write("\n};\n\n")

        def write_anim_array(name, anim_data):
            f.write(f"static const crash_pt crash_anim_{name}[{len(anim_data)}][CRASH_NUM_VERTS] = {{\n")
            for fi, frame in enumerate(anim_data):
                f.write(f"    /* Frame {fi} */\n    {{\n")
                for vi, (x, y, z) in enumerate(frame):
                    f.write(f"        {{ {x:.2f}f, {y:.2f}f, {z:.2f}f }},")
                    if (vi + 1) % 3 == 0:
                        f.write("\n")
                f.write("\n    },\n")
            f.write("};\n\n")

        write_anim_array("idle", anim_idle)
        write_anim_array("walk", anim_walk)
        write_anim_array("jump", anim_jump)
        write_anim_array("spin", anim_spin)
        write_anim_array("run", anim_run)
        write_anim_array("takeoff", anim_takeoff)
        write_anim_array("jump_up", anim_jump_up)
        write_anim_array("land", anim_land)

        f.write("#endif /* CRASH_MODEL_H */\n")

    print("[export_crash] Done! Generated source/crash_model.h successfully.")

if __name__ == "__main__":
    main()
