"""Extract the audited original integer quarter-wave table and byte evidence."""
import argparse
import hashlib
import json
from pathlib import Path
import struct

import cb3
from psx_native import Image, ORIGINAL_SHA256

ROOT = Path(__file__).resolve().parents[1]
TABLE_ADDRESS = 0x8005c91c
TABLE_COUNT = 1025


def table_source(image):
    if image.sha256 != ORIGINAL_SHA256:
        raise ValueError('not the audited SCUS_942.44 executable')
    raw = image.read(TABLE_ADDRESS, TABLE_COUNT * 2)
    values = struct.unpack('<1025h', raw)
    if values[0] != 0 or values[-1] != 4096 or any(a > b for a, b in zip(values, values[1:])):
        raise ValueError('original quarter-wave table is malformed')
    lines = ['/* Generated by tools/extract_gool_trig.py from audited SCUS_942.44. */',
             '#ifndef GOOL_TRIG_TABLE_H', '#define GOOL_TRIG_TABLE_H',
             '#include <stdint.h>',
             '#define GOOL_TRIG_SOURCE_SHA256 "'+image.sha256+'"',
             '#define GOOL_TRIG_TABLE_SHA256 "'+hashlib.sha256(raw).hexdigest()+'"',
             'static const int16_t gool_trig_quarter[1025] = {']
    lines += ['    '+', '.join(str(v) for v in values[n:n+16])+','
              for n in range(0, len(values), 16)]
    return '\n'.join(lines + ['};', '#endif', ''])


def evidence(image):
    if image.sha256 != ORIGINAL_SHA256:
        raise ValueError('not the audited SCUS_942.44 executable')
    raw = image.read(TABLE_ADDRESS, TABLE_COUNT * 2)
    return {'schema': 'psx-gool-trig-native/1',
        'analysis': 'offline-capstone-static-and-integer-fixture-replay',
        'source_sha256': image.sha256, 'source_file_size': image.file_size,
        'quarter_wave': {'address': TABLE_ADDRESS, 'entries': TABLE_COUNT,
                        'type': 'little-endian signed int16',
                        'sha256': hashlib.sha256(raw).hexdigest(), 'raw_hex': raw.hex()},
        'dispatch': [{'opcode': op, 'address': image.word(0x8005d120+4*op)}
                     for op in (0x2b, 0x2c)],
        'windows': {'store_sin_cos': image.disassemble(0x80039784, 0x800397cc),
                    'integer_sine': image.disassemble(0x800397cc, 0x80039828)},
        'semantics': ['Source upper operand is read before lower destination address.',
                      'Angle wraps modulo4096; quarter-wave amplitude is4096.',
                      'Cosine adds1024 with32bit wrapping then uses original sine routine.'],
        'limitations': ['Offline evidence, not REA provider Evidence.',
                       'Fixture replay does not model PS1 timing or gameplay reachability.']}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--exe', type=Path, default=Path(cb3.ISO)/'SCUS_942.44')
    args = parser.parse_args()
    image = Image.parse(args.exe.read_bytes())
    (ROOT/'source/gool_trig_table.h').write_text(table_source(image), encoding='utf-8')
    (ROOT/'tests/gool_trig_native_evidence.json').write_text(
        json.dumps(evidence(image), indent=2)+'\n', encoding='utf-8')
    print('Extracted original1025-entry integer quarter-wave table; source SHA verified.')


if __name__ == '__main__':
    main()
